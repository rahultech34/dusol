export function getDefaultPrograms(type?: "ug" | "pg" | "mba"): Program[] {
  if (!type) return DEFAULT_PROGRAMS;
  return DEFAULT_PROGRAMS.filter((p) => p.type === type);
}

export function getDefaultProgramById(id: string): Program | null {
  return DEFAULT_PROGRAMS.find((p) => p.id === id) || null;
}

export function getDefaultProgramBySlug(
  type?: "ug" | "pg" | "mba",
  slug?: string
): Program | null {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();

  // 1. Direct match on slug
  let found = DEFAULT_PROGRAMS.find((p) => {
    if (type && p.type !== type) return false;
    return p.slug === cleanSlug || p.id === cleanSlug;
  });
  if (found) return found;

  // 2. Try alias map
  const mapped = ACRONYM_MAP[cleanSlug];
  if (mapped) {
    found = DEFAULT_PROGRAMS.find((p) => {
      if (type && p.type !== type) return false;
      return p.slug === mapped || p.id === mapped;
    });
    if (found) return found;
  }

  // 3. Try stripped prefixes
  const stripped = cleanSlug.replace(/^(distance-|mba-)/, "");
  const strippedMapped = ACRONYM_MAP[stripped] || stripped;
  found = DEFAULT_PROGRAMS.find((p) => {
    if (type && p.type !== type) return false;
    return p.slug === strippedMapped || p.id === strippedMapped;
  });
  if (found) return found;

  // 4. Fallback search across any type if type was specified but not found
  if (type) {
    return getDefaultProgramBySlug(undefined, slug);
  }

  return null;
}
